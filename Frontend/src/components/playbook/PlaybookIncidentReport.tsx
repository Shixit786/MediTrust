import React, { useState, useMemo } from 'react';
import { MonoLabel } from '../ui/MonoLabel';
import { Printer, Download, Copy, FileText } from 'lucide-react';
import type { FusionResult, ShieldResult } from '../../types/analysis';

interface PlaybookIncidentReportProps {
  fusionResult: FusionResult | null;
  shieldResults: Partial<Record<string, ShieldResult>>;
}

export const PlaybookIncidentReport: React.FC<PlaybookIncidentReportProps> = React.memo(
  ({ fusionResult, shieldResults }) => {
    const [toastMessage, setToastMessage] = useState<string | null>(null);
    const [reportDate] = useState<Date>(() => new Date());

    // Deterministic or stable report metadata
    const reportData = useMemo(() => {
      const datePart = reportDate.toISOString().slice(0, 10).replace(/-/g, '');
      const reportId = `MT-${datePart}-0482`;
      const generatedAt = reportDate.toLocaleString('en-US', {
        dateStyle: 'medium',
        timeStyle: 'short',
      });

      const overallRisk = fusionResult
        ? fusionResult.overall_risk
        : Math.max(...Object.values(shieldResults).map((s) => s?.risk || 0), 0);

      const level = fusionResult
        ? fusionResult.level.toUpperCase()
        : overallRisk >= 80
          ? 'CRITICAL'
          : overallRisk >= 60
            ? 'HIGH'
            : overallRisk >= 30
              ? 'MEDIUM'
              : 'LOW';

      const pattern = fusionResult
        ? fusionResult.pattern
        : 'Multi-Vector Security Threat Assessment';

      const actions = fusionResult
        ? fusionResult.actions
        : [
          'Stop communication with the suspect sender immediately.',
          'Do not share any OTP, PIN, password, or financial credential.',
          'Contact the National Cyber Crime Helpline at 1930.',
        ];

      return {
        reportId,
        generatedAt,
        overallRisk,
        level,
        pattern,
        actions,
      };
    }, [fusionResult, shieldResults, reportDate]);

    // Plain-text export string
    const reportPlainText = useMemo(() => {
      let txt = `================================================================================
                    MEDITRUST INCIDENT INTELLIGENCE REPORT
================================================================================
REPORT ID      : ${reportData.reportId}
GENERATED AT   : ${reportData.generatedAt}
COMPOSITE RISK : ${reportData.overallRisk}/100 [${reportData.level}]
PATTERN        : ${reportData.pattern}
STATUS         : SIMULATED FORENSIC TELEMETRY · EARLY WARNING, NOT PROOF
--------------------------------------------------------------------------------
VECTORS EVALUATED:
`;

      const shields = ['job', 'voice', 'sim'] as const;
      shields.forEach((id) => {
        const s = shieldResults[id];
        if (s) {
          txt += `\n[${s.shield.toUpperCase()} SHIELD]
  Threat  : ${s.threat} (Risk: ${s.risk}/100, Level: ${s.level.toUpperCase()})
  Signals :
`;
          s.signals.slice(0, 3).forEach((sig) => {
            txt += `    - ${sig.name}: ${sig.detail}\n`;
          });
        }
      });

      if (fusionResult?.chain_steps) {
        txt += `\n--------------------------------------------------------------------------------
ATTACK CHAIN RECONSTRUCTION:
`;
        fusionResult.chain_steps.forEach((step) => {
          txt += `  [0${step.stepNumber}] ${step.title} -> ${step.status}\n`;
        });
      }

      txt += `\n--------------------------------------------------------------------------------
RECOMMENDED CONTAINMENT ACTIONS:
`;
      reportData.actions.forEach((act, idx) => {
        txt += `  ${idx + 1}. ${act}\n`;
      });

      txt += `\n--------------------------------------------------------------------------------
OFFICIAL EMERGENCY CONTACTS:
  - Cyber Crime Helpline 1930 (Toll-Free, Govt of India)
  - National Cyber Crime Reporting Portal: https://cybercrime.gov.in
--------------------------------------------------------------------------------
DISCLAIMER:
Early warning, not legal proof. Generated by MediTrust clinical safety demo.
================================================================================
`;
      return txt;
    }, [reportData, shieldResults, fusionResult]);

    const handleDownloadTxt = () => {
      const blob = new Blob([reportPlainText], { type: 'text/plain;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `meditrust-report-${reportData.reportId.toLowerCase()}.txt`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);

      setToastMessage('Report downloaded (.txt)');
      setTimeout(() => setToastMessage(null), 3500);
    };

    const handlePrint = () => {
      window.print();
    };

    const handleCopySummary = () => {
      navigator.clipboard.writeText(reportPlainText).then(() => {
        setToastMessage('Report summary copied to clipboard.');
        setTimeout(() => setToastMessage(null), 3500);
      }).catch(() => {
        setToastMessage('Failed to copy report text.');
        setTimeout(() => setToastMessage(null), 3500);
      });
    };

    return (
      <div className="relative flex flex-col gap-6">
        {/* Toast */}
        {toastMessage && (
          <div
            role="status"
            aria-live="polite"
            className="fixed bottom-6 right-6 z-50 bg-[#0A0A0A] text-white px-4 py-2.5 rounded-xl border border-[#0A0A0A] shadow-lg flex items-center gap-2.5 text-xs font-['Inter_Tight'] font-semibold"
          >
            <span className="w-2 h-2 rounded-full bg-[#16A34A]" />
            <span>{toastMessage}</span>
          </div>
        )}

        {/* Section Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-[#0A0A0A]/10 no-print">
          <div className="flex items-center gap-3">
            <FileText className="w-4 h-4 text-[#0037FF]" />
            <MonoLabel color="accent" className="text-xs font-semibold tracking-widest">
              INCIDENT REPORT // FORENSIC SUMMARY
            </MonoLabel>
          </div>

          {/* Action buttons */}
          <div className="flex flex-wrap items-center gap-3">
            <button
              type="button"
              onClick={handleCopySummary}
              className="px-3.5 py-2 rounded-xl bg-white hover:bg-[#F0F0F0] border border-[#0A0A0A] text-[#0A0A0A] font-mono-label text-xs font-semibold flex items-center gap-2 transition-colors cursor-pointer"
            >
              <Copy className="w-3.5 h-3.5" />
              <span>COPY SUMMARY</span>
            </button>

            <button
              type="button"
              onClick={handleDownloadTxt}
              className="px-3.5 py-2 rounded-xl bg-white hover:bg-[#F0F0F0] border border-[#0A0A0A] text-[#0A0A0A] font-mono-label text-xs font-semibold flex items-center gap-2 transition-colors cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>DOWNLOAD (.TXT)</span>
            </button>

            <button
              type="button"
              onClick={handlePrint}
              className="px-3.5 py-2 rounded-xl bg-[#0037FF] hover:bg-[#0030E0] text-white border border-[#0037FF] font-mono-label text-xs font-semibold flex items-center gap-2 transition-colors cursor-pointer"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>PRINT / SAVE AS PDF</span>
            </button>
          </div>
        </div>

        {/* Report Preview Document Card */}
        <div
          id="incident-report-printable"
          className="print-only-report p-6 sm:p-10 rounded-[20px] bg-white border border-[#0A0A0A] flex flex-col gap-8 select-text"
        >
          {/* Header row */}
          <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4 border-b border-[#0A0A0A] pb-6">
            <div>
              <span className="font-['Inter_Tight'] font-bold text-2xl tracking-tighter text-[#0A0A0A] block lowercase">
                meditrust
              </span>
              <span className="font-mono-label text-[11px] text-[#6B6F76]">
                CLINICAL FRAUD DEFENSE FORENSICS
              </span>
            </div>

            <div className="text-left sm:text-right font-mono-label text-xs text-[#0A0A0A] space-y-1">
              <div>
                REPORT ID: <strong className="font-bold">{reportData.reportId}</strong>
              </div>
              <div className="text-[#6B6F76]">{reportData.generatedAt}</div>
            </div>
          </div>

          {/* Verdict strip */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-6 p-5 rounded-[14px] bg-[#F0F0F0] border border-[#0A0A0A]/10">
            <div>
              <span className="font-mono-label text-[10px] text-[#6B6F76] block mb-1">
                COMPOSITE RISK
              </span>
              <span className="font-['Inter_Tight'] text-3xl font-light text-[#0A0A0A]">
                {reportData.overallRisk}
                <span className="text-sm font-mono-label text-[#6B6F76]">/100</span>
              </span>
            </div>

            <div>
              <span className="font-mono-label text-[10px] text-[#6B6F76] block mb-1">
                RISK SEVERITY
              </span>
              <span className="font-mono-label text-sm font-bold text-[#0A0A0A] inline-block px-2.5 py-1 rounded bg-white border border-[#0A0A0A]/20">
                {reportData.level}
              </span>
            </div>

            <div>
              <span className="font-mono-label text-[10px] text-[#6B6F76] block mb-1">
                PATTERN RECONSTRUCTION
              </span>
              <span className="font-['Inter_Tight'] text-sm font-medium text-[#0A0A0A]">
                {reportData.pattern}
              </span>
            </div>
          </div>

          {/* Per-Shield Evidence Summary */}
          <div className="space-y-4">
            <MonoLabel color="muted" className="text-[11px] block border-b border-[#0A0A0A]/10 pb-2">
              EVALUATED ATTACK VECTORS
            </MonoLabel>

            <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
              {(['job', 'voice', 'sim'] as const).map((id) => {
                const s = shieldResults[id];
                return (
                  <div
                    key={id}
                    className="p-4 rounded-xl border border-[#0A0A0A]/15 bg-[#F0F0F0]/40 flex flex-col justify-between gap-3"
                  >
                    <div>
                      <div className="flex items-center justify-between mb-2">
                        <span className="font-mono-label text-xs font-bold text-[#0A0A0A]">
                          {id.toUpperCase()} SHIELD
                        </span>
                        <span className="font-mono-label text-xs text-[#0A0A0A]">
                          {s ? `${s.risk}/100` : '--'}
                        </span>
                      </div>
                      <span className="font-['Inter_Tight'] text-xs font-medium text-[#6B6F76] block mb-3">
                        {s ? s.threat : 'No active vector telemetry'}
                      </span>
                      {s && (
                        <div className="space-y-1.5 text-xs text-[#6B6F76]">
                          {s.signals.slice(0, 3).map((sig, sIdx) => (
                            <div key={sIdx} className="leading-snug">
                              • <strong>{sig.name}:</strong> {sig.detail}
                            </div>
                          ))}
                        </div>
                      )}
                    </div>
                  </div>
                );
              })}
            </div>
          </div>

          {/* Recommended Actions */}
          <div className="space-y-3">
            <MonoLabel color="muted" className="text-[11px] block border-b border-[#0A0A0A]/10 pb-2">
              RECOMMENDED DEFENSIVE ACTIONS
            </MonoLabel>
            <div className="space-y-2">
              {reportData.actions.map((act, idx) => (
                <div key={idx} className="flex items-start gap-2.5 text-sm text-[#0A0A0A]">
                  <span className="font-mono-label text-xs font-bold text-[#0037FF] mt-0.5">
                    0{idx + 1}
                  </span>
                  <span>{act}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Footer & Disclaimer */}
          <div className="pt-6 border-t border-[#0A0A0A] flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 text-xs font-mono-label text-[#6B6F76]">
            <div>
              HELPLINE: 1930 · CYBERCRIME.GOV.IN
            </div>
            <div>
              EARLY WARNING, NOT PROOF · GENERATED BY MEDITRUST (DEMO)
            </div>
          </div>
        </div>
      </div>
    );
  }
);

PlaybookIncidentReport.displayName = 'PlaybookIncidentReport';
